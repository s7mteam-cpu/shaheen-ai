// the general / card / invite layouts of spec.ts (label + hint)
const spec = readFileSync(new URL("../src/design/spec.ts", import.meta.url), "utf8");
const lay = {};
for (const m of spec.matchAll(/^\s{2}(\w+): \{ label: "([^"]+)", hint: "([^"]+)"/gm)) lay[m[1]] = { l: m[2], h: m[3] };
const keep = (ids) => ids.filter((k) => lay[k]).map((k) => ({ id: k, t: `${lay[k].l}: ${lay[k].h}` }));
